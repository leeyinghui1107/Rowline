#!/usr/bin/env python3
"""
Assemble a distributable bundle.

The bundle contains the application binary, the assets it needs and a short
README.  It deliberately contains **no** asset from the original program: the
sprite sheet, the icons and the noise are all generated by this repository
(tools/make_sheet.py, tools/make_icons.py).

Usage:
    python3 tools/package.py                 # package the current platform
    python3 tools/package.py --list-targets
"""
import argparse
import os
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DIST = os.path.join(ROOT, "dist")

BIN_NAME = "rowline"
# Only what the running game loads: the sheet PNGs (multi-resolution) and
# the icon strips.  The noise texture, the artist guide and the SVG sources
# are build-time material and stay out of the bundle.
ASSETS = ["assets/sheet", "assets/icons"]
SKIP_SUFFIXES = (".bmp", ".svg")
SKIP_NAMES = ("rowline_sheet_guide.png",)

README = """Rowline -- cross-platform re-implementation
==========================================

This is an independent re-implementation of the behaviour of WinLinez v1.30
(Ivan Golubev, 1998-1999).  No original artwork, code or data is included;
the sprite sheet and the icons are generated by this repository's
tools/ scripts.  Rowline is not affiliated with or endorsed by
the author of the original game.

Controls
    left click          select a ball, then click a reachable cell
    F3                  toggle the "next set" preview
    F4                  new game
    F5                  toggle the statistics readout
    F6                  toggle the shape (figure) sprites
    F1 / F10            the command reference / the menu bar
    Ctrl+T              cycle theme (Classic / Dark / Light)
    Ctrl+M              reduce motion
    Ctrl+E              text size
    Ctrl+R              retro (fixed resolution) scaling
    Alt+F9              quit

macOS uses Cmd instead of Ctrl for the four presentation shortcuts.

The save file lives in the platform's application data directory
(`~/.local/share/rowline`, `~/Library/Application Support/rowline` or
`%APPDATA%\\rowline`) and is a human-readable RON document.
"""


def run(cmd, cwd=None):
    print("  $", " ".join(cmd))
    subprocess.check_call(cmd, cwd=cwd)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--list-targets", action="store_true")
    ap.add_argument("--out", default=DIST)
    ap.add_argument("--binary",
                    help="package this already-built binary instead of building")
    ap.add_argument("--skip-build", action="store_true",
                    help="reuse rust/target/release instead of running cargo")
    ap.add_argument("--zip", action="store_true",
                    help="also write <bundle>.zip next to the bundle directory")
    a = ap.parse_args()

    if a.list_targets:
        print("""
The Rust build produces a single binary for the host platform.  Release
bundles are produced per platform by running this script on that platform
(or by using the cross-compilation targets listed below).

    linux   x86_64-unknown-linux-gnu / aarch64-unknown-linux-gnu
    macos   x86_64-apple-darwin  / aarch64-apple-darwin
    windows x86_64-pc-windows-msvc
""".strip())
        return 0

    out = os.path.abspath(a.out)
    bundle = os.path.join(out, "%s-%s" % (BIN_NAME, sys.platform))
    if os.path.isdir(bundle):
        shutil.rmtree(bundle)
    os.makedirs(bundle)

    if a.binary:
        src = os.path.abspath(a.binary)
    else:
        if not a.skip_build:
            print("building the release binary")
            # Default features only: `--all-features` would also link the
            # software renderer, which the packaged GPU build never uses and
            # which costs about 150 KB.
            run(["cargo", "build", "--release", "-p", "rowline-app"],
                cwd=os.path.join(ROOT, "rust"))
        src = os.path.join(ROOT, "rust", "target", "release",
                           BIN_NAME + (".exe" if os.name == "nt" else ""))
    if not os.path.exists(src):
        print("  ! the binary was not produced at %s" % src)
        return 1
    shutil.copy2(src, os.path.join(bundle, os.path.basename(src)))
    os.chmod(os.path.join(bundle, os.path.basename(src)), 0o755)

    print("copying the assets")
    for rel in ASSETS:
        s = os.path.join(ROOT, rel)
        if not os.path.isdir(s):
            continue
        d = os.path.join(bundle, rel)
        os.makedirs(os.path.dirname(d), exist_ok=True)
        shutil.copytree(s, d)
    # The BMP copies are only needed by the C reference implementation
    # (SDL2 has no PNG loader); the guide and the SVG sources are authoring
    # material.  None of them are loaded at run time.
    for dirpath, _, files in os.walk(os.path.join(bundle, "assets")):
        for f in files:
            if f.endswith(SKIP_SUFFIXES) or f in SKIP_NAMES:
                os.remove(os.path.join(dirpath, f))

    with open(os.path.join(bundle, "README.txt"), "w", encoding="utf-8") as fh:
        fh.write(README)

    print("bundle ready: %s" % bundle)
    for dirpath, _, files in os.walk(bundle):
        for f in sorted(files):
            p = os.path.join(dirpath, f)
            print("  %-52s %8d B" % (os.path.relpath(p, bundle), os.path.getsize(p)))
    if a.zip:
        archive = shutil.make_archive(bundle, "zip", out,
                                      os.path.basename(bundle))
        print("archive ready: %s" % archive)
    return 0


if __name__ == "__main__":
    sys.exit(main())
