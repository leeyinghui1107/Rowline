#!/usr/bin/env python3
"""
Assemble a distributable bundle.

The bundle contains the application binary and a short README.  The sprite
sheet, icons and font are compiled into the binary, so there is no asset
directory to ship.  It deliberately contains **no** asset from the original
program: the art is generated by this repository's tools.

On macOS the executable is wrapped in `Rowline.app`, so a double-click starts
the game without a Terminal window behind it.  The binary inside is still the
same self-contained executable (all assets and the font are embedded).

Usage:
    python3 tools/package.py                 # package the current platform
    python3 tools/package.py --list-targets
"""
import argparse
import os
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DIST = os.path.join(ROOT, "dist")

BIN_NAME = "rowline"
APP_NAME = "Rowline"
BUNDLE_ID = "org.rowline.rowline"
# The directory name keeps the historical `sys.platform` spelling.
PLATFORM_KEYS = {"macos": "darwin", "linux": "linux", "windows": "win32"}


def host_platform():
    if sys.platform == "darwin":
        return "macos"
    if sys.platform.startswith("win"):
        return "windows"
    return "linux"

README = """Rowline -- cross-platform re-implementation
==========================================

This is an independent re-implementation of the behaviour of WinLinez v1.30
(Ivan Golubev, 1998-1999).  No original artwork, code or data is included;
the sprite sheet and the icons are generated by this repository's
tools/ scripts and compiled into the executable.  Rowline is not affiliated
with or endorsed by the author of the original game.

The download is self-contained: no other files are needed.  The UI font
(WenQuanYi Micro Hei, Apache-2.0) is embedded as well, so text renders
identically on systems without a Chinese font installed.

Starting it
    macOS       double-click Rowline.app (no Terminal window), or:
                    open Rowline.app
                The executable inside is Contents/MacOS/rowline.
    Linux       ./rowline
    Windows     rowline.exe

macOS note: Rowline.app is ad-hoc signed but not notarized.  If macOS blocks
the first launch after downloading the zip, right-click the app and choose
Open, or allow it under System Settings -> Privacy & Security.

Controls
    left click          select a ball, then click a reachable cell
    F4                  new game
    F5                  statistics
    F1                  help
    F10                 menu bar
    H                   high scores (menu mnemonic)
    Alt+F9              quit

The save file lives in the platform's application data directory
(`~/.local/share/rowline`, `~/Library/Application Support/rowline` or
`%APPDATA%\\rowline`) and is a small, hand-editable text document.
"""


def run(cmd, cwd=None):
    print("  $", " ".join(cmd))
    subprocess.check_call(cmd, cwd=cwd)


def workspace_version():
    """Read `version` from `[workspace.package]` in rust/Cargo.toml."""
    section = None
    path = os.path.join(ROOT, "rust", "Cargo.toml")
    try:
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line.startswith("["):
                    section = line
                elif section == "[workspace.package]" and line.startswith("version"):
                    return line.split("=", 1)[1].strip().strip('"')
    except OSError:
        pass
    return "0.1.0"


INFO_PLIST = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>zh_CN</string>
    <key>CFBundleDisplayName</key>
    <string>{name}</string>
    <key>CFBundleExecutable</key>
    <string>{binary}</string>
    <key>CFBundleIdentifier</key>
    <string>{bundle_id}</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleName</key>
    <string>{name}</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>{version}</string>
    <key>CFBundleVersion</key>
    <string>{version}</string>
    <key>LSApplicationCategoryType</key>
    <string>public.app-category.games</string>
    <key>LSMinimumSystemVersion</key>
    <string>11.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>NSPrincipalClass</key>
    <string>NSApplication</string>
</dict>
</plist>
"""


def make_macos_app(bundle, binary):
    """Wrap the executable in a .app so Finder launches it without Terminal."""
    app = os.path.join(bundle, APP_NAME + ".app")
    contents = os.path.join(app, "Contents")
    macos = os.path.join(contents, "MacOS")
    resources = os.path.join(contents, "Resources")
    os.makedirs(macos)
    os.makedirs(resources)

    target = os.path.join(macos, BIN_NAME)
    shutil.copy2(binary, target)
    os.chmod(target, 0o755)

    plist = INFO_PLIST.format(
        name=APP_NAME,
        binary=BIN_NAME,
        bundle_id=BUNDLE_ID,
        version=workspace_version(),
    )
    with open(os.path.join(contents, "Info.plist"), "w", encoding="utf-8") as fh:
        fh.write(plist)
    # Classic Mac OS type/creator; harmless and expected by some tools.
    with open(os.path.join(contents, "PkgInfo"), "w", encoding="ascii") as fh:
        fh.write("APPL????")

    # Ad-hoc signature: required on Apple Silicon for a bundle that was just
    # assembled on disk, and it keeps `open` from rejecting the app.  It is
    # not a Developer ID signature, so a downloaded copy still needs the
    # usual right-click -> Open on first launch.
    codesign = shutil.which("codesign")
    if codesign:
        proc = subprocess.run(
            [codesign, "--force", "--deep", "--sign", "-", app],
            capture_output=True, text=True,
        )
        if proc.returncode != 0:
            print("  ! ad-hoc codesign failed: %s" % proc.stderr.strip())
    return app


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--list-targets", action="store_true")
    ap.add_argument("--out", default=DIST)
    ap.add_argument("--binary",
                    help="package this already-built binary instead of building")
    ap.add_argument("--skip-build", action="store_true",
                    help="reuse rust/target/release instead of running cargo")
    ap.add_argument("--zip", action="store_true",
                    help="also write <bundle>.zip next to the bundle directory")
    ap.add_argument("--platform", choices=sorted(PLATFORM_KEYS),
                    help="package for this platform instead of the host "
                         "(use with --binary when cross-compiling)")
    a = ap.parse_args()

    if a.list_targets:
        print("""
The Rust build produces a single binary for the host platform.  Release
bundles are produced per platform by running this script on that platform
(or by using the cross-compilation targets listed below).

    linux   x86_64-unknown-linux-musl (static) / x86_64-unknown-linux-gnu
    macos   x86_64-apple-darwin  / aarch64-apple-darwin (universal)
    windows x86_64-pc-windows-gnu (mingw) / x86_64-pc-windows-msvc
""".strip())
        return 0

    out = os.path.abspath(a.out)
    platform = a.platform or host_platform()
    bundle = os.path.join(out, "%s-%s" % (BIN_NAME, PLATFORM_KEYS[platform]))
    if os.path.isdir(bundle):
        shutil.rmtree(bundle)
    os.makedirs(bundle)

    if a.binary:
        src = os.path.abspath(a.binary)
    else:
        if platform != host_platform():
            print("  ! cross-packaging %s requires --binary (build it first)"
                  % platform)
            return 1
        if not a.skip_build:
            print("building the release binary")
            # Default features only: `--all-features` would also link the
            # software renderer, which the packaged GPU build never uses and
            # which costs about 150 KB.
            run(["cargo", "build", "--release", "-p", "rowline-app"],
                cwd=os.path.join(ROOT, "rust"))
        src = os.path.join(ROOT, "rust", "target", "release",
                           BIN_NAME + (".exe" if platform == "windows" else ""))
    if not os.path.exists(src):
        print("  ! the binary was not produced at %s" % src)
        return 1
    if platform == "macos":
        make_macos_app(bundle, src)
    else:
        shutil.copy2(src, os.path.join(bundle, os.path.basename(src)))
        os.chmod(os.path.join(bundle, os.path.basename(src)), 0o755)

    with open(os.path.join(bundle, "README.txt"), "w", encoding="utf-8") as fh:
        fh.write(README)

    print("bundle ready: %s" % bundle)
    for dirpath, _, files in os.walk(bundle):
        for f in sorted(files):
            p = os.path.join(dirpath, f)
            print("  %-52s %8d B" % (os.path.relpath(p, bundle), os.path.getsize(p)))
    if a.zip:
        archive = shutil.make_archive(bundle, "zip", out,
                                      os.path.basename(bundle))
        print("archive ready: %s" % archive)
    return 0


if __name__ == "__main__":
    sys.exit(main())
