#!/usr/bin/env python3
"""Generate deterministic replay cases for the differential gate."""
import os, random, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import model as M

OUT = os.path.join(HERE, "cases")
os.makedirs(OUT, exist_ok=True)

def gen(seed, n_moves, name):
    rng = random.Random(seed)
    eng = M.Engine(M.Board(), score=0, seed=seed, model=M.RuleModel())
    eng.op_newgame()
    board = eng.board.cells[:]
    ops = []
    for _ in range(n_moves):
        occ = [i for i, v in enumerate(board) if v != 0]
        emp = [i for i, v in enumerate(board) if v == 0]
        if not occ or not emp:
            break
        src = rng.choice(occ)
        dst = rng.choice(emp)
        r0, c0 = M.rc(src); r1, c1 = M.rc(dst)
        ops.append(("move", r0, c0, r1, c1))
        # advance the reference so the board state stays consistent
        res = eng.op_move(r0, c0, r1, c1) if hasattr(eng, "op_move") else None
        board = eng.board.cells[:]
    lines = ["# generated by tools/replay/gen_cases.py",
             "seed %d" % seed]
    for o in ops:
        lines.append("op " + " ".join(str(x) for x in o))
    path = os.path.join(OUT, name)
    open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    return path, len(ops)

if __name__ == "__main__":
    specs = [(1, 40, "basic_001.trace"),
             (0xC0FFEE, 60, "basic_002.trace"),
             (123456789, 80, "basic_003.trace"),
             (0xDEADBEEF, 120, "stress_004.trace")]
    for seed, n, name in specs:
        p, k = gen(seed, n, name)
        print("wrote %-22s seed=0x%X ops=%d" % (name, seed, k))
    # a hand-made case exercising the illegal / no-path branches
    hand = ["# hand-made: illegal move (empty source), blocked destination",
            "seed 42",
            "board " + ("." * 81),
            "op move 0 0 4 4",     # source empty -> illegal
            "op click 2 2",
            "op setusefigures 1",
            "op newgame"]
    open(os.path.join(OUT, "edge_005.trace"), "w", encoding="utf-8").write("\n".join(hand) + "\n")
    print("wrote edge_005.trace")
